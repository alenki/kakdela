// Builds the loading screen's inline script (docs/CONVENTIONS.md, «До краёв: the loader»), minified with
// Next's own SWC into src/components/loader/loader-code.ts. Run it after editing any of its sources:
//   node scripts/build-loader.mjs
// Two parts:
//   the worker: assets-src/loader/liquid-sim.js (the physics), liquid-gl.js (WebGL2) and liquid-worker.js
//     (its loop), minified together, every /*glsl*/ shader squeezed first;
//   the page's: assets-src/loader/runtime.js (milestones, the honest needle, the guest's input, the clean
//     finish) and pour.js (the cover, the canvas, the worker's handshake), with the worker's code inlined
//     as a string where pour.js names __KD_LIQUID__ (it becomes a Blob: nothing is ever fetched).
// The minified code keeps two free names, __KD_ROUTES__ and __KD_BASE__, which loader-script.ts fills in
// from the routes config and the base path. Its styles are src/styles/loader.css.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { minify, loadBindings } = require("next/dist/build/swc");

const read = (f) => readFileSync(fileURLToPath(new URL(`../${f}`, import.meta.url)), "utf8");

// A shader without its comments and spare spaces (a preprocessor line keeps a line of its own). Both kinds
// of comment go in one pass, in the order they come; the space between two signs (a - -b) always stays.
export function squeeze(glsl) {
  const lines = glsl
    .replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  let out = "";
  for (const l of lines) {
    if (l.startsWith("#")) out += (out && !out.endsWith("\n") ? "\n" : "") + l + "\n";
    else
      out +=
        l
          .replace(/\s+/g, " ")
          .replace(/\s*([{}()[\];,=*/<>!&|?:])\s*/g, "$1")
          .replace(/(?<![+-])\s*([+-])\s*(?![+-])/g, "$1") + " ";
  }
  return out.trim();
}
const shaders = (js) => js.replace(/\/\*glsl\*\/\s*`([^`]*)`/g, (_, body) => JSON.stringify(squeeze(body)));

export async function build() {
  await loadBindings();
  const opts = { compress: true, mangle: true };
  const workerSrc = shaders(["assets-src/loader/liquid-sim.js", "assets-src/loader/liquid-gl.js", "assets-src/loader/liquid-worker.js"].map(read).join("\n"));
  const worker = (await minify(workerSrc, opts)).code;
  const pageSrc = ["assets-src/loader/runtime.js", "assets-src/loader/pour.js"].map(read).join("\n") + "\nKDLoader.boot();\n";
  let code = (await minify(pageSrc, opts)).code;
  for (const name of ["__KD_ROUTES__", "__KD_BASE__", "__KD_LIQUID__"]) if (!code.includes(name)) throw new Error(`${name} was lost in minification`);
  if (code.split("__KD_LIQUID__").length !== 2) throw new Error("__KD_LIQUID__ must appear exactly once");
  code = code.replace("__KD_LIQUID__", () => JSON.stringify(worker));
  // It is inlined in a <script>: nothing in it may end that tag or open a comment there.
  if (/<\/script|<!--/i.test(code)) throw new Error("the loader's code would break out of its <script>");
  return { code, sizes: { worker: worker.length, page: code.length - worker.length, total: code.length } };
}

// Single-quoted, so the code's own double-quoted strings stay as written (sessionStorage.setItem("kd-intro", …)).
const quoted = (c) =>
  "'" +
  c
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n") +
  "'";

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { code, sizes } = await build();
  writeFileSync(
    fileURLToPath(new URL("../src/components/loader/loader-code.ts", import.meta.url)),
    `// AUTO-GENERATED by scripts/build-loader.mjs from assets-src/loader/*.js. Do not edit by hand.\n` + `export const LOADER_CODE = ${quoted(code)};\n`,
  );
  console.log(`loader: ${sizes.total} B minified (the page's ${sizes.page} B, the worker's ${sizes.worker} B)`);
}
